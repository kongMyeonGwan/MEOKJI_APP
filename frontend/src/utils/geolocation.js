// 브라우저에 내 위치를 물어볼 때 쓰는 설정.
// 주소 선택 · 첫 화면 날씨 카드 · 추천 페이지가 같이 쓴다.
//
// 데스크톱은 와이파이를 훑어 구글에 물어보는 방식이라 느리다. 5초로는 모자라서
// 자주 시간 초과가 났다. 정확도는 동 단위면 충분하므로 高정확도는 끄고
// (켜면 더 느리다), 1분 안에 받아둔 위치가 있으면 그걸 그대로 쓴다.
//
// 한 군데 모아둔 이유는, 세 화면에 따로 적어뒀더니 한 곳만 고쳐지고
// 날씨 쪽 두 곳은 5초로 남아 있었기 때문이다.
export const GEO_OPTIONS = {
  timeout: 15000,
  enableHighAccuracy: false,
  maximumAge: 60000,
}

// 내 위치를 못 읽어서 다른 동네 날씨를 보여줄 때 띄울 알림 문구.
//
// 브라우저가 주는 code 는 1=권한 거부, 2=위치를 못 구함, 3=시간 초과 다.
// 셋을 "위치를 못 가져왔습니다" 하나로 뭉치면 뭘 고쳐야 할지 알 수가 없다.
//
// city 는 서버가 대신 준 동네 이름이다. 기본 자리를 설정에서 바꿀 수 있어서
// 문구에 박아두지 않고 응답에서 받은 값을 그대로 쓴다.
//
// 주소 선택 화면(AddressPicker)에도 같은 뜻의 문구가 있지만 거기는 "직접
// 골라주세요" 로 끝난다. 여기는 드롭다운이 없는 자리라 안내가 다르다.
export const weatherLocationAlert = (code, city) => {
  let reason = '위치를 가져오지 못했습니다.'

  if (code === 1) {
    reason = '위치 권한이 꺼져 있습니다. 주소창 왼쪽 자물쇠에서 위치를 허용해주세요.'
  }
  if (code === 2) {
    reason = '위치를 확인할 수 없습니다. 윈도우 설정에서 위치 서비스가 켜져 있는지 봐주세요.'
  }
  if (code === 3) {
    reason = '위치를 찾는 데 너무 오래 걸립니다. 잠시 뒤 다시 시도해주세요.'
  }

  return `${reason}\n\n지금은 ${city} 날씨를 보여드립니다. 마이페이지에서 사는 곳을 설정하면 그 동네 날씨로 바뀝니다.`
}
