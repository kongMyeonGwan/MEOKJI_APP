// Access Token 을 보관하는 곳.
//
// ================= 전에는 어떻게 했나 =================
//
// localStorage 나 sessionStorage 에 넣어뒀다. 새로고침해도 남아서 편했지만,
// 그 자리는 **자바스크립트면 누구나 읽을 수 있다.** 광고 스크립트 하나, 라이브러리
// 하나가 나쁜 코드를 들고 오면(XSS) 토큰이 그대로 털린다.
//
// ================= 지금은 =================
//
// 토큰을 이 파일의 변수 하나에만 들고 있는다. 화면을 새로 고치면 사라진다.
//
//   "그러면 F5 누를 때마다 로그아웃되는 거 아닌가?"
//
// 아니다. 서버가 로그인할 때 Refresh Token 을 HttpOnly 쿠키로 같이 심어뒀고,
// 그 쿠키는 자바스크립트가 읽을 수 없는 대신 브라우저가 알아서 들고 있다.
// 앱이 켜질 때 /api/auth/refresh 를 한 번 부르면 쿠키만으로 새 Access Token 을
// 받아온다 (App.jsx 참고).
//
//   F5 → 메모리의 토큰 사라짐 → /api/auth/refresh → 새 토큰 → 로그인 복원
//
// 즉 "읽히면 위험한 값" 은 메모리에, "오래 남아야 하는 값" 은 자바스크립트가
// 못 보는 쿠키에 둔 것이다.
//
// ================= 사용자 정보(user)는? =================
//
// 그것도 저장하지 않는다. 위 refresh 응답에 회원 정보가 같이 와서 따로 둘 이유가
// 없어졌다. 저장해두면 서버에서 닉네임이 바뀌어도 옛 값이 화면에 남는 문제도 있었다.

// 지금 로그인한 사람의 Access Token. 로그인 안 했으면 null.
//
// 이 파일을 import 하는 쪽은 모두 같은 변수를 본다 (모듈은 한 번만 실행된다).
// 그래서 화면(App.jsx)에서 넣은 값을 axios 설정(client.js)에서 꺼내 쓸 수 있다.
let accessToken = null

// 토큰 꺼내기. 로그인 안 했으면 null
export const getToken = () => {
  return accessToken
}

// 토큰 넣기 (로그인 성공 · 토큰 재발급)
export const setToken = (token) => {
  accessToken = token
}

// 토큰 지우기 (로그아웃)
export const removeToken = () => {
  accessToken = null
}
