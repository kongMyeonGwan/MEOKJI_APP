-- FREE_POSTS : PK 를 IDENTITY -> 시퀀스(FREE_SEQ) 로 바꾼다
--
-- 언제 실행하나요?
--   09_add_free_posts.sql 의 옛 버전(IDENTITY)으로 FREE_POSTS 를 만든 DB 에서
--   딱 한 번 실행합니다. 지금의 01_schema.sql / 09_add_free_posts.sql 로 만든
--   DB 라면 이미 시퀀스라서 이 파일이 필요 없습니다.
--
-- 실행 계정 : MEOKJI_APP
-- 실행 방법 : 파일 전체 선택 후 Alt+X (DBeaver) / F5 (SQL Developer)
--             ※ Ctrl+Enter 는 한 문장만 실행합니다
--
-- 무엇이 바뀌나요?
--   1. free_posts.id 에서 IDENTITY 를 뗀다. 컬럼 · PK · 들어 있는 글은 그대로다.
--      IDENTITY 가 속으로 만들어 둔 시퀀스(ISEQ$$_...)는 이때 같이 사라진다.
--   2. FREE_SEQ 시퀀스를 만든다. 지금 가장 큰 id 다음 번호부터 시작한다 —
--      1 부터 시작하면 이미 있는 글과 번호가 겹쳐 INSERT 가 PK 위반으로 막힌다.
--
--   JPA(FreePostEntity)의 @SequenceGenerator(sequenceName = "FREE_SEQ",
--   allocationSize = 1) 와 짝이다. 그래서 INCREMENT BY 1 이다.
--
-- 되돌리려면 (글이 있으면 START WITH 를 MAX(id)+1 로 맞춰야 한다)
--   DROP SEQUENCE free_seq;
--   ALTER TABLE free_posts MODIFY (id GENERATED BY DEFAULT AS IDENTITY (START WITH <MAX(id)+1>));
-- =========================================================


-- ---------------------------------------------------------
-- 0. 실행 전 확인
--    identity_column 이 YES 면 실행 대상, NO 면 이미 바뀐 것이다.
-- ---------------------------------------------------------
SELECT column_name, identity_column
FROM   user_tab_columns
WHERE  table_name = 'FREE_POSTS'
AND    column_name = 'ID';


-- ---------------------------------------------------------
-- 1. IDENTITY 떼기
-- ---------------------------------------------------------
ALTER TABLE free_posts MODIFY (id DROP IDENTITY);


-- ---------------------------------------------------------
-- 2. 시퀀스 만들기 — 지금 가장 큰 id 다음부터
--    START WITH 에는 변수를 못 쓰므로 PL/SQL 로 문장을 만들어 실행한다.
-- ---------------------------------------------------------
DECLARE
    v_start NUMBER;
BEGIN
    SELECT NVL(MAX(id), 0) + 1 INTO v_start FROM free_posts;

    EXECUTE IMMEDIATE 'CREATE SEQUENCE free_seq START WITH ' || v_start
                   || ' INCREMENT BY 1 NOCACHE';

    DBMS_OUTPUT.PUT_LINE('FREE_SEQ starts with ' || v_start);
END;
/

COMMENT ON COLUMN free_posts.id IS 'PK. FREE_SEQ 시퀀스로 채운다 (IDENTITY 아님)';


