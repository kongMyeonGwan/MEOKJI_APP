package com.meokji.api.auth.service;

/**
 * 비밀번호 재설정 (이메일 인증번호). 실제 코드는 PasswordResetServiceImpl 에 있다.
 *
 *   1단계 send   : 6자리 인증번호를 만들어 메일로 보낸다
 *   2단계 verify : 받은 인증번호가 맞는지 확인한다
 *   3단계 change : 새 비밀번호로 바꾸고, 잠긴 계정도 같이 푼다
 *
 * <p>왜 AuthService 와 따로 뒀나 — 가입 · 로그인과 달리 이쪽은 "코드를 만들고
 * 메일을 보내고 만료를 재는" 일이 전부다. 한 클래스에 합치면 AuthServiceImpl 이
 * 메일 발송과 코드 만료까지 들고 있게 된다.
 *
 * <p>세 메서드가 돌려줄 값이 없어 전부 void 다. 성공하면 조용히 끝나고,
 * 실패하면 ApiException 을 던진다. 컨트롤러는 예외가 안 나면 성공으로 보고
 * 안내 문장을 만들어 보낸다.
 *
 * <p>단계마다 email 을 또 받는 이유 — 로그인하지 못하는 사람이 쓰는 기능이라
 * 토큰이 없다. "누구의 비밀번호인가" 를 매번 email 로 알려줘야 한다.
 */
public interface PasswordResetService {

    /**
     * 1단계. 인증번호를 만들어 메일로 보낸다.
     *
     * 가입되지 않은 이메일이면 404 를 던진다. "메일을 보냈다" 고만 하고 넘어가면
     * 오타를 낸 사용자가 오지 않는 메일을 계속 기다리게 되므로, 알려주는 쪽을 골랐다.
     * (대신 2 · 3단계는 반대다 — 그쪽은 가입 여부를 구별해 주지 않는다)
     *
     * 같은 사람이 짧은 사이에 여러 번 부르면 429 를 던진다 (메일 폭탄 방지).
     * 몇 초를 기다려야 하는지도 같이 알려준다.
     */
    void send(String email);

    /**
     * 2단계. 인증번호가 맞는지 확인한다. 틀렸거나 만료면 에러.
     *
     * 성공하면 그 코드에 "확인됨" 표시를 남긴다. 3단계가 그 표시를 본다.
     */
    void verify(String email, String code);

    /**
     * 3단계. 새 비밀번호로 바꾼다.
     *
     * 2단계를 통과한 코드인지 다시 확인한다. 여기만 열려 있으면 번호 확인을
     * 건너뛰고 비밀번호를 바꿀 수 있기 때문이다.
     *
     * 바꾸고 나서 코드는 지운다. 남겨두면 같은 코드로 비밀번호를 계속 바꿀 수 있다.
     */
    void change(String email, String code, String newPassword);
}
