-- =========================================================
-- 8. NOTICES : 공지사항 게시판
--
--    운영자가 쓰고 회원은 읽기만 한다. RECIPE_REVIEWS 와 달리
--    MEAL_HISTORIES 에서 파생되지 않는 독립 게시판이다.
--    좋아요·댓글도 붙지 않는다 (읽기 전용 공지).
--
--    ! "운영자만 작성" 은 USERS.USER_LEVEL(1=관리자) 로 가린다. 다만 그 판단을
--      DB 가 하지는 않는다 — 등급을 보고 막는 것은 서비스 계층(라우터의
--      get_admin_user)이다. FK 하나로 등급을 강제할 수단이 DB 에는 없다.
-- =========================================================
CREATE TABLE notices (
    id          NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,      -- PK
    user_id     NUMBER(19)          NOT NULL,                              -- 작성한 운영자 계정
    title       VARCHAR2(200 CHAR)  NOT NULL,                              -- 공지 제목
    content     VARCHAR2(4000)      NOT NULL,                              -- 본문. 바이트 기준 4000 = 한글 약 1333자
    view_count  NUMBER(10)          DEFAULT 0 NOT NULL,                    -- 조회수. 상세 조회 때 1 증가
    pinned_yn   CHAR(1)             DEFAULT 'N' NOT NULL,                  -- 'Y' = 목록 상단 고정. 삭제 플래그가 아니다
    use_yn      CHAR(1)             DEFAULT 'Y' NOT NULL,                  -- 'N' = 삭제된 공지. 목록·상세에서 걸러야 한다
    created_at  TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  -- 등록 시각 (UTC)
    updated_at  TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  -- 마지막 수정 시각 (UTC)
    CONSTRAINT pk_notices            PRIMARY KEY (id),
    CONSTRAINT fk_notices_user       FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_notices_view_count CHECK (view_count >= 0),
    CONSTRAINT ck_notices_pinned_yn  CHECK (pinned_yn IN ('Y', 'N')),
    CONSTRAINT ck_notices_use_yn     CHECK (use_yn IN ('Y', 'N'))
);
-- 분류(카테고리) 컬럼을 두지 않는다.
--   한때 '안내' · '점검' · '업데이트' 배지를 그리는 CATEGORY 가 있었다
--   (04_notices_and_games.sql 로 추가 -> 07_drop_notice_category.sql 로 제거).
--   값을 강제하는 장치가 없었고(CHECK 도, 분류 목록 표도 없음) 화면도 '점검'
--   하나만 경고색이라, 그 한 가지를 위해 컬럼을 유지할 이유가 없었다.
--   공지는 공지 하나로 끝낸다.

-- 본문을 CLOB 이 아니라 VARCHAR2(4000) 으로 둔다.
--   4000 은 바이트 기준이라 한글이 약 1333자까지 들어간다. 공지 한 건이 그보다
--   길어질 일이 없고, VARCHAR2 면 목록 조회에서 본문을 그대로 실어도 LOB 을
--   따로 읽지 않는다 — 공지 목록은 화면이 그 자리에서 펼쳐서 본문을 같이 싣는다.
--
--   VARCHAR2(4000 CHAR) 로는 쓸 수 없다. 표준 모드의 상한이 4000 바이트라
--   CHAR 기준으로는 1000 자가 최대이고, 그렇게 적으면 오히려 더 짧아진다.
--
--   RECIPE_REVIEWS.CONTENT 는 반대로 CLOB 이다. 후기는 회원이 쓰는 글이라
--   길이를 예상할 수 없고, 목록에서는 앞 200자만 잘라 보내기 때문이다.

-- fk_notices_user 에만 ON DELETE CASCADE 가 없다 (fk_reviews_meal 과 함께 둘뿐).
-- 운영자 계정이 사라진다고 공지가 같이 사라지면 안 되기 때문이다.
-- 공지는 서비스 전체를 향한 글이라 작성자 계정보다 오래 남아야 한다.

-- 목록 조회 전용. WHERE use_yn='Y' ORDER BY pinned_yn DESC, created_at DESC 를 그대로 태운다.
-- use_yn 을 선두에 두는 이유는 파일 상단 [3] 참고 (모든 조회에 use_yn='Y' 가 붙는다)
CREATE INDEX idx_notices_created ON notices (use_yn, pinned_yn DESC, created_at DESC);

-- FK 컬럼 인덱스. "이 운영자가 쓴 공지" 조회보다는, 부모(USERS) 변경 시
-- 자식 테이블 전체를 잠그지 않게 하려는 목적이 크다
CREATE INDEX idx_notices_user ON notices (user_id, use_yn);

COMMENT ON TABLE notices IS '공지사항. 운영자만 작성(서비스 계층에서 강제), 조회는 Guest 가능. 삭제는 use_yn=N';


-- =========================================================
-- 9. GAME_HISTORIES : 미니게임 플레이 기록
--
--    쌓기만 하는 로그다. 한번 들어간 행을 수정하거나 지우지 않는다.
--    그래서 USE_YN 도, PK 도 없다 (상단 [5] 참고).
--    조회는 항상 "이 회원의 기록" 단위이지 "그 판 하나" 단위가 아니다.
--
--    ! 나중에 "이 판만 삭제" 가 필요해지면 USE_YN 만 추가해서는 안 된다.
--      행을 지목할 수단이 없어 그 회원 기록이 통째로 꺼진다.
--      ID 컬럼(IDENTITY)과 PK 를 함께 추가해야 한다.
-- =========================================================
CREATE TABLE game_histories (
    user_id     NUMBER(19)   NOT NULL,                                     -- 플레이한 회원. 회원 삭제 시 함께 삭제된다
    game_type   CHAR(1)      DEFAULT 'A' NOT NULL,                        -- 게임 종류. A=음식 월드컵 B=취향 밸런스 C=랜덤 돌림판
    game_point  NUMBER(10)   DEFAULT 0 NOT NULL,                           -- 이 판에서 획득한 점수
    created_at  TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  -- 플레이 시각 (UTC 고정)
    CONSTRAINT fk_game_histories_user   FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_game_histories_type   CHECK (game_type IN ('A', 'B', 'C')),
    CONSTRAINT ck_game_histories_point  CHECK (game_point >= 0)
);
-- game_type 은 화면의 게임 세 개와 하나씩 짝이다.
--
--   A  음식 월드컵   (/game/worldcup)  후보를 둘씩 비교해 좁힌다
--   B  취향 밸런스   (/game/balance)   질문 다섯 개로 조건을 만든다
--   C  랜덤 돌림판   (/roulette)       운에 맡긴다
--
-- 글자 하나로 두는 이유는 이 표가 '누가 · 무엇을 · 언제' 만 남기는 로그라
-- 종류 이름까지 매 행에 넣을 이유가 없어서다. 글자와 게임의 대응은
-- backend-spring 의 GameServiceImpl.recordPlay 한 곳에만 적어둔다.
--
-- 게임이 늘어나면 이 CHECK 에 글자를 추가해야 INSERT 가 통과한다.
-- (제약을 빼면 아무 글자나 들어가므로, 값을 늘리는 쪽으로 관리한다)

-- "내 게임 기록" 조회 전용. use_yn 이 없으므로 (user_id, created_at) 두 컬럼이면 된다
CREATE INDEX idx_game_histories_user ON game_histories (user_id, created_at DESC);

COMMENT ON TABLE game_histories IS '미니게임 플레이 기록. 수정·삭제하지 않는 누적 로그라 USE_YN·PK 없음';


-- =========================================================
-- 10. RECIPE_LIKES : 찜한 레시피
--     로그인한 회원만 찜할 수 있다. 비로그인 상태에서 하트를 누르면
--     화면이 로그인으로 보내므로 '회원 없는 찜' 이라는 상태가 없다.
-- =========================================================
CREATE TABLE recipe_likes (
    id          NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,         -- PK
    user_id     NUMBER(19)          NOT NULL,                                 -- 찜한 회원. 회원이 사라지면 찜도 같이 사라진다
    food_name   VARCHAR2(150 CHAR)  NOT NULL,                                 -- 음식 이름. 마스터 테이블 없이 문자열로 저장 (MEAL_HISTORIES 와 같은 길이)
    use_yn      CHAR(1)             DEFAULT 'Y' NOT NULL,                     -- 'N' = 찜 해제. 다시 찜할 수 있어야 해서 물리 삭제하지 않는다
    created_at  TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  -- 찜한 시각 (UTC)
    CONSTRAINT pk_recipe_likes        PRIMARY KEY (id),
    CONSTRAINT fk_recipe_likes_user   FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_recipe_likes_use_yn CHECK (use_yn IN ('Y', 'N'))
);
-- 음식 id 가 아니라 이름을 저장하는 이유
--   추천 결과를 DB 에 저장하지 않으므로(설계 원칙 §13) 서버가 만들어준 음식
--   id 가 존재하지 않는다. 화면도 이미 이름으로 레시피를 연다(/recipe/김치찌개).
--   USER_BANS.INGREDIENT_NAME 과 같은 판단이다.

-- 찜을 껐다 켰다 하는 것이 막히면 안 되므로 UNIQUE 를 함수 기반으로 건다 ([2] 참고)
CREATE UNIQUE INDEX uq_recipe_likes ON recipe_likes (
    CASE WHEN use_yn = 'Y' THEN user_id   END,
    CASE WHEN use_yn = 'Y' THEN food_name END
);

-- "내 찜 목록" 조회용. 위 인덱스는 선두가 표현식이라 이 조회에 쓰이지 않는다
CREATE INDEX idx_recipe_likes_user ON recipe_likes (user_id, use_yn);

COMMENT ON TABLE  recipe_likes IS '찜한 레시피. 해제는 use_yn=N. 로그인한 회원만 찜할 수 있다';
COMMENT ON COLUMN recipe_likes.food_name IS '음식 이름. 추천 결과를 저장하지 않으므로 id 가 없다';


