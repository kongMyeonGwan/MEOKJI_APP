-- =========================================================
-- 8. NOTICES : 공지사항 게시판
--
--    운영자가 쓰고 회원은 읽기만 한다. RECIPE_REVIEWS 와 달리
--    MEAL_HISTORIES 에서 파생되지 않는 독립 게시판이다.
--    좋아요·댓글도 붙지 않는다 (읽기 전용 공지).
--
--    ! USERS 에는 관리자 구분 컬럼이 없다. 따라서 "운영자만 작성" 을
--      DB 가 강제하지 못하고 서비스 계층이 막아야 한다.
-- =========================================================
CREATE TABLE notices (
    id          NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,      -- PK
    user_id     NUMBER(19)          NOT NULL,                              -- 작성한 운영자 계정
    title       VARCHAR2(200 CHAR)  NOT NULL,                              -- 공지 제목
    content     CLOB                NOT NULL,                              -- 본문. VARCHAR2(4000)은 한글 1333자에서 막혀 CLOB 을 쓴다
    view_count  NUMBER(10)          DEFAULT 0 NOT NULL,                    -- 조회수. 상세 조회 때 1 증가
    pinned_yn   CHAR(1)             DEFAULT 'N' NOT NULL,                  -- 'Y' = 목록 상단 고정. 삭제 플래그가 아니다
    use_yn      CHAR(1)             DEFAULT 'Y' NOT NULL,                  -- 'N' = 삭제된 공지. 목록·상세에서 걸러야 한다
    created_at  TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  -- 등록 시각 (UTC)
    updated_at  TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  -- 마지막 수정 시각 (UTC)
    CONSTRAINT pk_notices            PRIMARY KEY (id),
    CONSTRAINT fk_notices_user       FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_notices_view_count CHECK (view_count >= 0),
    CONSTRAINT ck_notices_pinned_yn  CHECK (pinned_yn IN ('Y', 'N')),
    CONSTRAINT ck_notices_use_yn     CHECK (use_yn IN ('Y', 'N'))
);
-- fk_notices_user 에만 ON DELETE CASCADE 가 없다 (fk_reviews_meal 과 함께 둘뿐).
-- 운영자 계정이 사라진다고 공지가 같이 사라지면 안 되기 때문이다.
-- 공지는 서비스 전체를 향한 글이라 작성자 계정보다 오래 남아야 한다.

-- 목록 조회 전용. WHERE use_yn='Y' ORDER BY pinned_yn DESC, created_at DESC 를 그대로 태운다.
-- use_yn 을 선두에 두는 이유는 파일 상단 [3] 참고 (모든 조회에 use_yn='Y' 가 붙는다)
CREATE INDEX idx_notices_created ON notices (use_yn, pinned_yn DESC, created_at DESC);

-- FK 컬럼 인덱스. "이 운영자가 쓴 공지" 조회보다는, 부모(USERS) 변경 시
-- 자식 테이블 전체를 잠그지 않게 하려는 목적이 크다
CREATE INDEX idx_notices_user ON notices (user_id, use_yn);

COMMENT ON TABLE notices IS '공지사항. 운영자만 작성(서비스 계층에서 강제), 조회는 Guest 가능. 삭제는 use_yn=N';


-- =========================================================
-- 9. GAME_HISTORIES : 미니게임 플레이 기록
--
--    쌓기만 하는 로그다. 한번 들어간 행을 수정하거나 지우지 않는다.
--    그래서 USE_YN 도, PK 도 없다 (상단 [5] 참고).
--    조회는 항상 "이 회원의 기록" 단위이지 "그 판 하나" 단위가 아니다.
--
--    ! 나중에 "이 판만 삭제" 가 필요해지면 USE_YN 만 추가해서는 안 된다.
--      행을 지목할 수단이 없어 그 회원 기록이 통째로 꺼진다.
--      ID 컬럼(IDENTITY)과 PK 를 함께 추가해야 한다.
-- =========================================================
CREATE TABLE game_histories (
    user_id     NUMBER(19)   NOT NULL,                                     -- 플레이한 회원. 회원 삭제 시 함께 삭제된다
    game_type   CHAR(1)      DEFAULT 'A' NOT NULL,                        -- 게임 종류. 허용값은 ck_game_histories_type 참고
    game_point  NUMBER(10)   DEFAULT 0 NOT NULL,                           -- 이 판에서 획득한 점수
    created_at  TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  -- 플레이 시각 (UTC 고정)
    CONSTRAINT fk_game_histories_user   FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_game_histories_type   CHECK (game_type IN ('A')),
    CONSTRAINT ck_game_histories_point  CHECK (game_point >= 0)
);
-- ck_game_histories_type 은 지금 'A' 하나만 허용한다.
-- 게임 종류가 늘어나면 이 CHECK 에 값을 추가해야 INSERT 가 통과한다.
-- (제약을 빼면 아무 글자나 들어가므로, 값을 늘리는 쪽으로 관리한다)

-- "내 게임 기록" 조회 전용. use_yn 이 없으므로 (user_id, created_at) 두 컬럼이면 된다
CREATE INDEX idx_game_histories_user ON game_histories (user_id, created_at DESC);

COMMENT ON TABLE game_histories IS '미니게임 플레이 기록. 수정·삭제하지 않는 누적 로그라 USE_YN·PK 없음';


