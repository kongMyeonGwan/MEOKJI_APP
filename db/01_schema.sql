-- =========================================================
-- 1. USERS : 회원 정보
-- =========================================================
CREATE TABLE users (
    id                NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    email             VARCHAR2(255 CHAR)  NOT NULL,
    password_hash     VARCHAR2(255 CHAR)  NOT NULL,
    nickname          VARCHAR2(50 CHAR)   NOT NULL,
    login_fail_count  NUMBER(3)           DEFAULT 0 NOT NULL,
    is_locked         NUMBER(1)           DEFAULT 0 NOT NULL,
    locked_at         TIMESTAMP(6),
    created_at        TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    updated_at        TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_users             PRIMARY KEY (id),
    CONSTRAINT uq_users_email       UNIQUE (email),
    CONSTRAINT uq_users_nickname    UNIQUE (nickname),
    CONSTRAINT ck_users_is_locked   CHECK (is_locked IN (0, 1)),
    CONSTRAINT ck_users_fail_count  CHECK (login_fail_count >= 0)
);
-- password_hash 는 bcrypt 해시만 저장 (평문 금지)
-- is_locked 0=FALSE, 1=TRUE
-- email / nickname 은 UNIQUE 제약이 인덱스를 자동 생성하므로 별도 인덱스 불필요

COMMENT ON TABLE users IS '회원. 로그인 실패 20회 시 is_locked=1로 잠금';


-- =========================================================
-- 2. VERIFICATION_CODES : 이메일 인증번호 (비밀번호 재설정용 OTP)
-- =========================================================
CREATE TABLE verification_codes (
    id             NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    user_id        NUMBER(19)          NOT NULL,
    code_hash      VARCHAR2(255 CHAR)  NOT NULL,
    purpose        VARCHAR2(30 CHAR)   NOT NULL,
    expires_at     TIMESTAMP(6) NOT NULL,
    attempt_count  NUMBER(3)           DEFAULT 0 NOT NULL,
    used_at        TIMESTAMP(6),
    created_at     TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_vc          PRIMARY KEY (id),
    CONSTRAINT fk_vc_user     FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_vc_purpose  CHECK (purpose IN ('PASSWORD_RESET', 'EMAIL_VERIFY', 'ACCOUNT_UNLOCK')),
    CONSTRAINT ck_vc_attempt  CHECK (attempt_count >= 0)
);
-- code_hash  : 6자리 원문은 이메일로만 발송, DB에는 해시만
-- expires_at : 생성 시각 + 5분
-- used_at    : 인증 성공 시각. NULL 이면 아직 사용 안 한 코드

CREATE INDEX idx_vc_user_purpose ON verification_codes (user_id, purpose, created_at DESC);

COMMENT ON TABLE verification_codes IS '이메일 OTP. used_at IS NULL AND expires_at > SYSTIMESTAMP 인 것만 유효';


-- =========================================================
-- 3. USER_BANS : 못 먹거나 먹기 싫은 재료
--    별도 INGREDIENTS 마스터 테이블 없이 재료명을 문자열로 저장
-- =========================================================
CREATE TABLE user_bans (
    id               NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    user_id          NUMBER(19)          NOT NULL,
    ingredient_name  VARCHAR2(100 CHAR)  NOT NULL,
    ban_type         VARCHAR2(20 CHAR)   NOT NULL,
    created_at       TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_user_bans       PRIMARY KEY (id),
    CONSTRAINT fk_user_bans_user  FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_user_bans       UNIQUE (user_id, ingredient_name),
    CONSTRAINT ck_user_bans_type  CHECK (ban_type IN ('DISLIKE', 'ALLERGY'))
);
-- uq_user_bans 인덱스의 선두 컬럼이 user_id 이므로
-- 내 Ban 전체 조회도 이 인덱스를 사용한다 -> 추가 인덱스 불필요

COMMENT ON TABLE user_bans IS 'Ban 재료. ALLERGY는 DISLIKE보다 강한 제한으로 취급';


-- =========================================================
-- 4. MEAL_HISTORIES : 사용자가 최종 확정한 식사 (이 프로젝트의 핵심 DB)
--    확정 당시의 레시피/재료/대체재료를 그대로 스냅샷 저장 (이후 UPDATE 안 함)
-- =========================================================
CREATE TABLE meal_histories (
    id                NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    user_id           NUMBER(19)          NOT NULL,
    food_name         VARCHAR2(150 CHAR)  NOT NULL,
    recipe_name       VARCHAR2(200 CHAR),
    recipe_json       CLOB                NOT NULL,
    ingredients_json  CLOB                NOT NULL,
    substitutes_json  CLOB,
    estimated_cost    NUMBER(10),
    selected_at       TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_meal              PRIMARY KEY (id),
    CONSTRAINT fk_meal_user         FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_meal_cost         CHECK (estimated_cost IS NULL OR estimated_cost >= 0),
    CONSTRAINT ck_meal_recipe_json  CHECK (recipe_json IS JSON),
    CONSTRAINT ck_meal_ingr_json    CHECK (ingredients_json IS JSON),
    CONSTRAINT ck_meal_subs_json    CHECK (substitutes_json IS NULL OR substitutes_json IS JSON)
);
-- food_name        : recipe_json 안에도 있으나 목록 조회를 위해 컬럼으로 승격
-- recipe_json      : cook_time_minutes, servings, difficulty, steps[]
-- ingredients_json : [{name, quantity, unit}, ...]
-- substitutes_json : [{original, substitute, reason}, ...]
-- estimated_cost   : 확정 시점 예상 재료비 (원)

CREATE INDEX idx_meal_user_selected ON meal_histories (user_id, selected_at DESC);

COMMENT ON TABLE meal_histories IS '확정된 식사 스냅샷. AI가 나중에 다른 레시피를 생성해도 이 행은 변하지 않음';


-- =========================================================
-- 5. POSTS : 음식/레시피 공유 게시판
-- =========================================================
CREATE TABLE posts (
    id           NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    user_id      NUMBER(19)          NOT NULL,
    title        VARCHAR2(200 CHAR)  NOT NULL,
    content      CLOB                NOT NULL,
    food_name    VARCHAR2(150 CHAR),
    recipe_json  CLOB,
    view_count   NUMBER(10)          DEFAULT 0 NOT NULL,
    created_at   TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    updated_at   TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_posts              PRIMARY KEY (id),
    CONSTRAINT fk_posts_user         FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_posts_view_count   CHECK (view_count >= 0),
    CONSTRAINT ck_posts_recipe_json  CHECK (recipe_json IS NULL OR recipe_json IS JSON)
);
-- food_name / recipe_json : History에서 커뮤니티로 공유할 때 자동 입력

CREATE INDEX idx_posts_created ON posts (created_at DESC);
CREATE INDEX idx_posts_user    ON posts (user_id);

COMMENT ON TABLE posts IS '게시판. 조회는 Guest 가능, 작성은 로그인 사용자만, 수정/삭제는 작성자만';


-- =========================================================
-- 6. POST_LIKES : 좋아요 (사용자당 게시글당 1회)
-- =========================================================
CREATE TABLE post_likes (
    id          NUMBER(19)  GENERATED BY DEFAULT AS IDENTITY,
    user_id     NUMBER(19)  NOT NULL,
    post_id     NUMBER(19)  NOT NULL,
    created_at  TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_post_likes       PRIMARY KEY (id),
    CONSTRAINT fk_post_likes_user  FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_post_likes_post  FOREIGN KEY (post_id) REFERENCES posts (id) ON DELETE CASCADE,
    CONSTRAINT uq_post_likes       UNIQUE (user_id, post_id)
);
-- uq_post_likes : 프론트뿐 아니라 DB 레벨에서도 중복 좋아요를 차단

CREATE INDEX idx_post_likes_post ON post_likes (post_id);
-- 게시글별 좋아요 수 COUNT 용 (uq_post_likes 인덱스는 선두가 user_id 라서 별도 필요)

COMMENT ON TABLE post_likes IS '좋아요. 자기 게시글에도 가능, 중복은 uq_post_likes가 차단';


-- =========================================================
-- 7. COMMENTS : 댓글 (MVP에서는 대댓글 없음 -> parent_comment_id 없음)
-- =========================================================
CREATE TABLE comments (
    id          NUMBER(19)           GENERATED BY DEFAULT AS IDENTITY,
    post_id     NUMBER(19)           NOT NULL,
    user_id     NUMBER(19)           NOT NULL,
    content     VARCHAR2(1000 CHAR)  NOT NULL,
    created_at  TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    updated_at  TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_comments       PRIMARY KEY (id),
    CONSTRAINT fk_comments_post  FOREIGN KEY (post_id) REFERENCES posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_comments_user  FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_comments_post ON comments (post_id, created_at);

COMMENT ON TABLE comments IS '댓글. 대댓글 미지원(MVP)';


