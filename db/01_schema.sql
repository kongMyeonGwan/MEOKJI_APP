    updated_at   TIMESTAMP(6)        DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,

    CONSTRAINT pk_notices PRIMARY KEY (id),

    CONSTRAINT fk_notices_user
        FOREIGN KEY (user_id)
        REFERENCES users (id),

    CONSTRAINT ck_notices_view_count
        CHECK (view_count >= 0),

    CONSTRAINT ck_notices_pinned_yn
        CHECK (pinned_yn IN ('Y', 'N')),

    CONSTRAINT ck_notices_use_yn
        CHECK (use_yn IN ('Y', 'N'))
);

CREATE INDEX idx_notices_created
ON notices (pinned_yn, created_at DESC);

CREATE INDEX idx_notices_user
ON notices (user_id);

COMMENT ON TABLE notices IS '공지사항 게시판';


