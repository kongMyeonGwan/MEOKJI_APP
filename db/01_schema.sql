--             DBeaver 설정 주의:
--             Preferences > Editors > SQL Editor > SQL Processing 에서
--             "Blank line is statement delimiter" 를 Never 로 두세요.
--             (켜져 있으면 CREATE TABLE 문이 중간에서 잘려 ORA-00900이 납니다.
--              이 파일은 CREATE TABLE 내부에 빈 줄을 두지 않아 기본값에서도 동작합니다)
--
-- 이 파일은 "빈 스키마에 처음부터 만드는" 스크립트입니다.
-- 이미 구버전 테이블이 있는 DB는 db/02_migrate_v2.sql 을 실행하세요.
-- 재실행할 때는 00_drop_all.sql 을 먼저 실행하세요.
--
-- 설계 원칙
--   - 음식/레시피/재료 Master 테이블을 만들지 않는다 (AI가 동적 생성)
--   - 검색 결과, 추천 후보, 날씨, 상품 가격은 저장하지 않는다
--   - 사용자가 확정한 결과만 MEAL_HISTORIES에 스냅샷으로 남긴다
--   - 레시피 후기(RECIPE_REVIEWS)는 반드시 자기 MEAL_HISTORIES 에서 파생된다
--   - 삭제는 물리 삭제가 아니라 USE_YN='N' 갱신이다 (아래 참고)
--
-- Oracle 작성 규칙
--   - PK        : NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (Sequence+Trigger 미사용)
--   - 문자열    : VARCHAR2(n CHAR)  <- CHAR 필수. 생략 시 바이트 기준이라 한글이 1/3만 들어감
--   - Boolean   : NUMBER(1) + CHECK (0=FALSE, 1=TRUE)
--   - Y/N 플래그: CHAR(1) + CHECK ('Y','N')
--   - 날짜/시간 : TIMESTAMP(6) + SYS_EXTRACT_UTC(SYSTIMESTAMP). 항상 UTC로 저장한다.
--                python-oracledb가 타임존 정보를 저장/조회 양방향에서 버리기 때문에
--                WITH TIME ZONE을 써도 파이썬에서는 offset을 볼 수 없다.
--                오히려 세션 타임존에 따라 값이 조용히 어긋나므로 UTC 단일 정책으로 간다.
--   - JSON      : CLOB + CHECK (... IS JSON)
--   - 제약조건  : 전부 명시적으로 이름 부여 (미지정 시 SYS_C0099999 형태가 되어 판독 불가)
--
-- =========================================================
-- USE_YN (논리 삭제) 규칙 — 반드시 읽으세요
-- =========================================================
--
-- UI의 "삭제" / "회원 탈퇴" 버튼은 DELETE 문을 실행하지 않는다.
-- USE_YN 을 'N' 으로 UPDATE 해서 화면에서만 사라지게 한다.
--
--   [1] 모든 조회에 WHERE use_yn = 'Y' 를 붙여야 한다.
--       하나라도 빠지면 삭제한 데이터가 그대로 노출된다.
--       좋아요 COUNT 와 JOIN 에서 특히 자주 빠뜨린다.
--
--   [2] UNIQUE 는 제약조건이 아니라 함수 기반 인덱스로 건다.
--       평범한 UNIQUE 를 쓰면 'N' 으로 남은 행이 자리를 차지해서
--       좋아요 재클릭 / Ban 재등록 / 탈퇴한 이메일 재가입이 전부
--       ORA-00001 로 막힌다.
--       CASE WHEN use_yn='Y' THEN col END 으로 감싸면 'N' 행은 모든
--       키 컬럼이 NULL 이 되어 인덱스에서 빠지고, 살아있는 행끼리만
--       유일성을 본다.
--
--   [3] 함수 기반 UNIQUE 인덱스는 WHERE col = :v 조회에 쓰이지 않는다.
--       그래서 조회용 일반 인덱스를 (col, use_yn) 으로 따로 만든다.
--
--   [4] FK 의 ON DELETE CASCADE 와 참조 차단은 진짜 DELETE 에만 작동한다.
--       UPDATE use_yn='N' 은 DB 입장에서 그냥 값 수정이라 아무 반응도 없다.
--       따라서 아래 두 가지는 서비스 계층이 책임진다.
--         - 회원 탈퇴 시 그 회원의 하위 데이터도 함께 'N' 으로 UPDATE
--         - 살아있는 후기가 달린 MEAL_HISTORIES 는 'N' 으로 못 바꾸게 차단
--       FK 를 그대로 두는 이유는 삭제 차단이 아니라, 없는 행을 참조하거나
--       남의 히스토리를 자기 후기로 다는 것을 DB 가 막아주기 때문이다.
--
--   [5] VERIFICATION_CODES 와 GAME_HISTORIES 에는 USE_YN 이 없다.
--       OTP 는 사용자가 삭제하는 데이터가 아니고 used_at / expires_at 로
--       이미 생명주기를 관리한다. 붙여봐야 영원히 'Y' 만 들어간다.
--       GAME_HISTORIES 는 쌓기만 하고 수정·삭제하지 않는 순수 로그다.
--       지우지 않으므로 USE_YN 이 필요 없고, 행 하나를 지목할 일도 없어
--       PK 도 두지 않는다. 이 둘은 세트로 간다 — USE_YN 을 나중에 붙이려면
--       행을 특정할 PK 부터 있어야 한다.
-- =========================================================


-- =========================================================
-- 1. USERS : 회원 정보
-- =========================================================
CREATE TABLE users (
    id                NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,         -- PK. 모든 하위 테이블이 user_id 로 참조하는 회원 식별자
    email             VARCHAR2(255 CHAR)  NOT NULL,                                 -- 로그인 ID. 탈퇴하지 않은 회원끼리만 유일 (uq_users_email)
    password_hash     VARCHAR2(255 CHAR)  NOT NULL,                                 -- bcrypt 해시. 평문 비밀번호는 DB·로그 어디에도 남기지 않는다
    nickname          VARCHAR2(50 CHAR)   NOT NULL,                                 -- 게시판·댓글에 노출되는 이름. 이메일 대신 이 값만 보여준다
    gender            VARCHAR2(10 CHAR),                                            -- MALE / FEMALE / OTHER. NULL = "선택 안 함" (필수 입력 아님)
    address_sido      VARCHAR2(30 CHAR),                                            -- 시·도 표시용. "서울특별시" — 화면 출력에만 쓴다
    address_sigungu   VARCHAR2(30 CHAR),                                            -- 시·군·구 표시용. "강남구" — 화면 출력에만 쓴다
    latitude          NUMBER(9,6),                                                  -- 위도. 날씨 API 를 실제로 호출하는 값 (가입 시 주소에서 변환)
    longitude         NUMBER(9,6),                                                  -- 경도. latitude 와 한 쌍으로만 의미가 있다
    login_fail_count  NUMBER(3)           DEFAULT 0 NOT NULL,                       -- 연속 로그인 실패 횟수. 로그인에 성공하면 0 으로 초기화
    is_locked         NUMBER(1)           DEFAULT 0 NOT NULL,                       -- 계정 잠금 여부. 0=정상 1=잠김. 실패 20회 누적 시 1
    locked_at         TIMESTAMP(6),                                                 -- 잠긴 시각. 안내 문구·해제 판단에 쓴다. 정상 계정은 NULL
    use_yn            CHAR(1)             DEFAULT 'Y' NOT NULL,                     -- 'N' = 탈퇴 회원. 행은 남기고 조회에서만 제외한다
    created_at        TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  -- 가입 시각 (UTC 고정)
    updated_at        TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  -- 회원정보 마지막 수정 시각 (UTC 고정)
    CONSTRAINT pk_users             PRIMARY KEY (id),
    CONSTRAINT ck_users_is_locked   CHECK (is_locked IN (0, 1)),
    CONSTRAINT ck_users_fail_count  CHECK (login_fail_count >= 0),
    CONSTRAINT ck_users_use_yn      CHECK (use_yn IN ('Y', 'N')),
    CONSTRAINT ck_users_gender      CHECK (gender IS NULL OR gender IN ('MALE', 'FEMALE', 'OTHER')),
    CONSTRAINT ck_users_latitude    CHECK (latitude  IS NULL OR latitude  BETWEEN  -90 AND  90),
    CONSTRAINT ck_users_longitude   CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);
-- 주소를 '표시용 문자열'과 '좌표' 두 벌로 나눠 가진 이유
--   OpenWeather 는 한국 시·군·구를 도시명 문자열로 찾지 못한다.
--   그래서 회원가입 때 주소를 좌표로 한 번 변환해 저장하고, 이후 날씨 조회는
--   좌표로만 호출한다. 화면에 "서울특별시 강남구" 를 보여주는 건 앞의 두 컬럼이다.

-- UNIQUE 를 제약조건이 아니라 함수 기반 인덱스로 거는 이유는 파일 상단 [2] 참고
CREATE UNIQUE INDEX uq_users_email    ON users (CASE WHEN use_yn = 'Y' THEN email    END);
CREATE UNIQUE INDEX uq_users_nickname ON users (CASE WHEN use_yn = 'Y' THEN nickname END);

-- 로그인(email 조회) / 닉네임 중복 확인용. 위 인덱스는 이 조회에 쓰이지 않는다 ([3] 참고)
CREATE INDEX idx_users_email    ON users (email, use_yn);
CREATE INDEX idx_users_nickname ON users (nickname, use_yn);

COMMENT ON TABLE users IS '회원. 로그인 20회 실패 시 is_locked=1, 탈퇴 시 use_yn=N';


-- =========================================================
-- 2. VERIFICATION_CODES : 이메일 인증번호 (비밀번호 재설정용 OTP)
--    USE_YN 없음 — 이유는 파일 상단 [5] 참고
-- =========================================================
CREATE TABLE verification_codes (
    id             NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,         -- PK
    user_id        NUMBER(19)          NOT NULL,                                 -- 이 코드를 발급받은 회원. 회원 삭제 시 함께 삭제된다
    code_hash      VARCHAR2(255 CHAR)  NOT NULL,                                 -- 6자리 인증번호의 해시. 원문은 이메일로만 보내고 저장하지 않는다
    purpose        VARCHAR2(30 CHAR)   NOT NULL,                                 -- 코드 용도. PASSWORD_RESET / EMAIL_VERIFY / ACCOUNT_UNLOCK
    expires_at     TIMESTAMP(6) NOT NULL,                                        -- 만료 시각 = 생성 시각 + 5분. 지나면 무효
    attempt_count  NUMBER(3)           DEFAULT 0 NOT NULL,                       -- 이 코드에 대한 입력 시도 횟수. 무차별 대입을 끊는 기준
    used_at        TIMESTAMP(6),                                                 -- 인증 성공 시각. NULL 이면 아직 쓰지 않은 코드 (1회용)
    created_at     TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  -- 발급 시각 (UTC)
    CONSTRAINT pk_vc          PRIMARY KEY (id),
    CONSTRAINT fk_vc_user     FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_vc_purpose  CHECK (purpose IN ('PASSWORD_RESET', 'EMAIL_VERIFY', 'ACCOUNT_UNLOCK')),
    CONSTRAINT ck_vc_attempt  CHECK (attempt_count >= 0)
);
CREATE INDEX idx_vc_user_purpose ON verification_codes (user_id, purpose, created_at DESC);

COMMENT ON TABLE verification_codes IS '이메일 OTP. used_at IS NULL AND expires_at > SYSTIMESTAMP 인 것만 유효';


-- =========================================================
-- 3. USER_BANS : 못 먹거나 먹기 싫은 재료
--    별도 INGREDIENTS 마스터 테이블 없이 재료명을 문자열로 저장
-- =========================================================
CREATE TABLE user_bans (
    id               NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,         -- PK
    user_id          NUMBER(19)          NOT NULL,                                 -- Ban 을 등록한 회원
    ingredient_name  VARCHAR2(100 CHAR)  NOT NULL,                                 -- 못 먹거나 싫은 재료명. 마스터 테이블 없이 문자열로 저장
    ban_type         VARCHAR2(20 CHAR)   NOT NULL,                                 -- DISLIKE(싫어함) / ALLERGY(알레르기). ALLERGY 를 더 강하게 취급
    use_yn           CHAR(1)             DEFAULT 'Y' NOT NULL,                     -- 'N' = 사용자가 뺀 Ban. 다시 등록할 수 있어야 해서 물리 삭제하지 않는다
    created_at       TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  -- 등록 시각 (UTC)
    CONSTRAINT pk_user_bans        PRIMARY KEY (id),
    CONSTRAINT fk_user_bans_user   FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_user_bans_type   CHECK (ban_type IN ('DISLIKE', 'ALLERGY')),
    CONSTRAINT ck_user_bans_use_yn CHECK (use_yn IN ('Y', 'N'))
);
-- 오이를 뺐다가 다시 등록하는 것이 막히면 안 되므로 UNIQUE 를 함수 기반으로 건다
CREATE UNIQUE INDEX uq_user_bans ON user_bans (
    CASE WHEN use_yn = 'Y' THEN user_id         END,
    CASE WHEN use_yn = 'Y' THEN ingredient_name END
);

-- "내 Ban 전체 조회" 용. 위 인덱스는 선두가 표현식이라 이 조회에 쓰이지 않는다
CREATE INDEX idx_user_bans_user ON user_bans (user_id, use_yn);

COMMENT ON TABLE user_bans IS 'Ban 재료. ALLERGY는 DISLIKE보다 강한 제한으로 취급';


-- =========================================================
-- 4. MEAL_HISTORIES : 사용자가 최종 확정한 식사 (이 프로젝트의 핵심 DB)
--    확정 당시의 레시피/재료/대체재료를 그대로 스냅샷 저장 (이후 UPDATE 안 함)
-- =========================================================
CREATE TABLE meal_histories (
    id                NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,         -- PK. 후기(RECIPE_REVIEWS)가 meal_history_id 로 참조한다
    user_id           NUMBER(19)          NOT NULL,                                 -- 이 식사를 확정한 회원. 후기 작성 시 소유권 검사의 기준이 된다
    food_name         VARCHAR2(150 CHAR)  NOT NULL,                                 -- 음식 이름. recipe_json 안에도 있으나 목록 조회를 위해 컬럼으로 승격
    recipe_name       VARCHAR2(200 CHAR),                                           -- 레시피 제목. AI 가 이름을 붙이지 않았으면 NULL
    recipe_json       CLOB                NOT NULL,                                 -- 조리법 스냅샷. cook_time_minutes, servings, difficulty, steps[]
    ingredients_json  CLOB                NOT NULL,                                 -- 재료 스냅샷. [{name, quantity, unit}, ...]
    substitutes_json  CLOB,                                                         -- 대체 재료. [{original, substitute, reason}, ...]. 없으면 NULL
    estimated_cost    NUMBER(10),                                                   -- 확정 시점의 예상 재료비 (원). 계산할 수 없으면 NULL
    use_yn            CHAR(1)             DEFAULT 'Y' NOT NULL,                     -- 'N' = 사용자가 지운 기록. 후기가 달려 있으면 서비스 계층이 막는다
    selected_at       TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  -- 사용자가 이 식사를 확정한 시각 (UTC). 히스토리 정렬 기준
    CONSTRAINT pk_meal              PRIMARY KEY (id),
    CONSTRAINT fk_meal_user         FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_meal_id_user      UNIQUE (id, user_id),
    CONSTRAINT ck_meal_cost         CHECK (estimated_cost IS NULL OR estimated_cost >= 0),
    CONSTRAINT ck_meal_use_yn       CHECK (use_yn IN ('Y', 'N')),
    CONSTRAINT ck_meal_recipe_json  CHECK (recipe_json IS JSON),
    CONSTRAINT ck_meal_ingr_json    CHECK (ingredients_json IS JSON),
    CONSTRAINT ck_meal_subs_json    CHECK (substitutes_json IS NULL OR substitutes_json IS JSON)
);
-- uq_meal_id_user 는 중복 방지용이 아니다. id 는 PK 라 이미 유일하다.
-- RECIPE_REVIEWS 가 (meal_history_id, user_id) 합성 FK 로 이 테이블을 참조하는데,
-- Oracle 은 PK 또는 UNIQUE 인 컬럼 조합만 참조 대상으로 허용하기 때문에 필요하다.
-- 이 덕분에 "남의 히스토리를 내 후기로 공유"하는 것이 DB 레벨에서 막힌다.

CREATE INDEX idx_meal_user_selected ON meal_histories (user_id, use_yn, selected_at DESC);

COMMENT ON TABLE meal_histories IS '확정된 식사 스냅샷. AI가 나중에 다른 레시피를 생성해도 이 행은 변하지 않음';


-- =========================================================
-- 5. RECIPE_REVIEWS : 레시피 추천(후기) 게시판
--
--    "직접 만들어본 요리만 글을 쓸 수 있다" 는 규칙을 FK 로 강제한다.
--    글쓰기 화면은 내 MEAL_HISTORIES 목록에서 하나를 고르는 것으로 시작한다.
--
--    food_name / recipe_json 컬럼을 두지 않는다.
--    MEAL_HISTORIES 가 이미 "확정 당시 스냅샷, 이후 UPDATE 없음" 이라 값이
--    변할 일이 없다. 복사해 두면 두 값이 어긋날 여지만 생기므로 JOIN 으로 읽는다.
-- =========================================================
CREATE TABLE recipe_reviews (
    id               NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,         -- PK. 좋아요·댓글이 review_id 로 참조한다
    user_id          NUMBER(19)          NOT NULL,                                 -- 글쓴이. meal_history_id 와 한 쌍으로 소유권 검증에도 쓰인다 (fk_reviews_meal)
    meal_history_id  NUMBER(19)          NOT NULL,                                 -- 어떤 식사에 대한 후기인가. 음식명·레시피는 이 FK 로 JOIN 해서 읽는다
    title            VARCHAR2(200 CHAR)  NOT NULL,                                 -- 글 제목
    content          CLOB                NOT NULL,                                 -- 본문. 목록 응답에는 앞 200자만 잘라서 내려보낸다
    view_count       NUMBER(10)          DEFAULT 0 NOT NULL,                       -- 조회수. 상세 조회 때 1 증가
    use_yn           CHAR(1)             DEFAULT 'Y' NOT NULL,                     -- 'N' = 삭제된 글. 목록·상세·좋아요·댓글 조회에서 모두 걸러야 한다
    created_at       TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  -- 작성 시각 (UTC). 게시판 목록 정렬 기준
    updated_at       TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  -- 마지막 수정 시각 (UTC)
    CONSTRAINT pk_recipe_reviews      PRIMARY KEY (id),
    CONSTRAINT fk_reviews_user        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_reviews_meal        FOREIGN KEY (meal_history_id, user_id)
                                      REFERENCES meal_histories (id, user_id),
    CONSTRAINT ck_reviews_view_count  CHECK (view_count >= 0),
    CONSTRAINT ck_reviews_use_yn      CHECK (use_yn IN ('Y', 'N'))
);
-- fk_reviews_meal 이 (meal_history_id, user_id) 두 컬럼을 '한 쌍'으로 참조하는 이유
--   user_id 를 중복해서 들고 있는 것이 아니라, 소유권을 DB가 검증하게 만드는 장치다.
--   meal_history_id 하나만 참조하면 "존재하는 기록이기만 하면 통과" 지만,
--   쌍으로 참조하면 "그 기록의 주인이 나여야 통과" 가 된다.
--
--   후기 등록 요청에서 클라이언트가 보내는 값은 meal_history_id 뿐이다.
--   user_id 는 JWT 에서 서버가 꺼내므로 위조할 수 없다. 그래서 Postman 으로
--   남의 meal_history_id 를 넣어 보내면 (그 id, 내 user_id) 조합이
--   MEAL_HISTORIES 에 없어서 INSERT 자체가 거부된다.
--
--   서비스 계층도 같은 검사를 한다(post_service.create_post 에서 404 로 끊는다).
--   그쪽은 응답 코드를 제대로 주기 위한 것이고, 이 FK 는 관리자 도구·배치·직접 SQL 등
--   앞으로 생길 다른 경로까지 한 번에 막는 최후 방어선이다.

-- fk_reviews_meal 에 ON DELETE 절이 없다 = 기본값 차단.
-- 후기가 달린 식사 기록은 물리 삭제되지 않는다.
-- 다만 우리는 물리 삭제를 쓰지 않으므로, 논리 삭제(use_yn='N') 차단은
-- 서비스 계층이 "살아있는 후기가 있는가" 를 확인해서 막아야 한다 ([4] 참고).

-- 같은 식사로 후기를 두 번 쓰지 못하게. 지운 뒤 다시 쓰는 것은 허용해야 하므로 함수 기반
CREATE UNIQUE INDEX uq_reviews_meal ON recipe_reviews (
    CASE WHEN use_yn = 'Y' THEN meal_history_id END
);

CREATE INDEX idx_reviews_created ON recipe_reviews (use_yn, created_at DESC);
CREATE INDEX idx_reviews_user    ON recipe_reviews (user_id, use_yn);

COMMENT ON TABLE recipe_reviews IS '레시피 후기 게시판. 자기 MEAL_HISTORIES 에서만 작성 가능. 조회는 Guest 가능';


-- =========================================================
-- 6. REVIEW_LIKES : 좋아요 (사용자당 후기당 1회)
-- =========================================================
CREATE TABLE review_likes (
    id          NUMBER(19)  GENERATED BY DEFAULT AS IDENTITY,                 -- PK
    user_id     NUMBER(19)  NOT NULL,                                         -- 좋아요를 누른 회원
    review_id   NUMBER(19)  NOT NULL,                                         -- 좋아요 대상 후기
    use_yn      CHAR(1)     DEFAULT 'Y' NOT NULL,                             -- 'Y'=누른 상태, 'N'=취소한 상태. 좋아요 수는 'Y' 만 센다
    created_at  TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  -- 처음 누른 시각 (UTC)
    CONSTRAINT pk_review_likes        PRIMARY KEY (id),
    CONSTRAINT fk_review_likes_user   FOREIGN KEY (user_id)   REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_review_likes_review FOREIGN KEY (review_id) REFERENCES recipe_reviews (id) ON DELETE CASCADE,
    CONSTRAINT ck_review_likes_use_yn CHECK (use_yn IN ('Y', 'N'))
);
-- 좋아요는 눌렀다 취소했다를 반복하는 데이터다.
-- 평범한 UNIQUE 였다면 취소('N') 후 재클릭이 ORA-00001 로 막힌다. 함수 기반이어야 한다.
CREATE UNIQUE INDEX uq_review_likes ON review_likes (
    CASE WHEN use_yn = 'Y' THEN user_id   END,
    CASE WHEN use_yn = 'Y' THEN review_id END
);

-- 후기별 좋아요 수 COUNT 용. 반드시 use_yn='Y' 만 세야 한다
CREATE INDEX idx_review_likes_review ON review_likes (review_id, use_yn);

COMMENT ON TABLE review_likes IS '좋아요. 취소는 use_yn=N. 자기 후기에도 가능';


