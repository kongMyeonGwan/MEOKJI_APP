-- 무엇이 바뀌나요?
--   테이블이 하나 늘어납니다. 9개 -> 10개.
--
--   찜은 그동안 브라우저(localStorage)에만 있었습니다. 그래서
--     - 기기나 브라우저를 바꾸면 안 따라오고
--     - 한 브라우저를 여러 사람이 쓰면 앞사람 찜이 보였습니다
--       (저장 키에 회원 구분이 없었습니다)
--
--   로그인한 회원만 찜할 수 있게 바뀝니다. 비로그인 상태에서 하트를 누르면
--   로그인 화면으로 갑니다. 그래서 '회원 없는 찜' 이라는 상태 자체가 없고,
--   브라우저에 남아 있던 값은 옮기지 않고 버립니다.
--
-- 되돌리려면
--   DROP TABLE recipe_likes PURGE;
