-- =========================================================
-- USERS 에 Refresh Token 컬럼 추가 (v2.4 -> v2.5)
--
-- 언제 실행하나요?
--   이미 01_schema.sql 로 USERS 가 만들어진 DB 에서 딱 한 번 실행합니다.
--
-- 실행 계정 : MEOKJI_APP
-- 실행 방법 : 파일 전체 선택 후 Alt+X (DBeaver) / F5 (SQL Developer)
--             ※ Ctrl+Enter 는 한 문장만 실행합니다
--
-- 무엇이 바뀌나요?
--   USERS 에 컬럼 2개가 늘어납니다. 테이블 개수는 그대로입니다.
--
--     refresh_token_hash   현재 유효한 Refresh Token 의 SHA-256 해시
--     refresh_expires_at   그 토큰이 만료되는 시각 (UTC)
--
--   기존 회원은 둘 다 NULL 입니다 = "로그인 기록 없음". 다음 로그인 때 채워집니다.
--
-- =========================================================
-- 왜 REFRESH_TOKEN 테이블을 따로 안 만드나
-- =========================================================
--   한 사람이 동시에 여러 기기에서 로그인하는 것을 지원하려면 별도 표가 맞습니다
--   (회원 1 : 토큰 N). 이 프로젝트는 "한 사람당 가장 최근 로그인 1개" 로 충분해서
--   USERS 에 컬럼 2개를 붙입니다.
--
--   대신 이런 동작이 됩니다 — PC 에서 로그인한 뒤 폰에서 로그인하면 PC 쪽
--   Refresh Token 이 덮어써져서 PC 는 30분 뒤(Access Token 만료) 로그아웃됩니다.
--   표를 나누면 안 그렇습니다. 지금은 이 동작을 받아들입니다.
--
-- =========================================================
-- 왜 토큰 원문이 아니라 해시를 저장하나
-- =========================================================
--   Refresh Token 은 14일 동안 "이 사람이 맞다" 를 증명하는 값입니다.
--   원문을 그대로 넣어두면 DB 가 한 번 새는 순간 그 값을 복사해 쿠키에 넣는 것만으로
--   남의 계정에 들어갈 수 있습니다. 비밀번호를 평문으로 저장하지 않는 것과 같은 이유입니다.
--
--   해시를 저장하면 DB 에 있는 값으로는 아무것도 못 합니다. 단방향이라 되돌릴 수 없고,
--   서버는 "쿠키로 들어온 토큰을 해시해서 DB 값과 같은지" 만 비교하면 됩니다.
--
--   비밀번호와 달리 BCrypt 가 아니라 SHA-256 을 쓰는 이유
--     BCrypt 는 일부러 느리게 만든 함수입니다. 사람이 고른 비밀번호("1234")는
--     짧고 뻔해서 공격자가 전부 넣어볼 수 있고, 그래서 한 번 계산에 시간을 끌어
--     대입을 막아야 합니다.
--     Refresh Token 은 서버가 만든 JWT 라 길고 무작위입니다. 전부 넣어보는 공격이
--     애초에 불가능해서 느리게 만들 이유가 없고, /refresh 를 부를 때마다 BCrypt 를
--     돌리면 그만큼 응답만 느려집니다.
--
-- =========================================================
-- 왜 VARCHAR2(64) 인가
-- =========================================================
--   SHA-256 결과는 32바이트이고, 이것을 16진수 글자로 적으면 항상 정확히 64글자입니다.
--   길이가 고정이라 넉넉히 잡을 필요가 없습니다.
--   (토큰 원문을 저장했다면 JWT 길이가 들쭉날쭉해서 VARCHAR2(1000) 쯤 필요했습니다)
--
-- 되돌리려면
--   ALTER TABLE users DROP COLUMN refresh_token_hash;
--   ALTER TABLE users DROP COLUMN refresh_expires_at;
-- =========================================================


-- ---------------------------------------------------------
-- 0. 실행 전 확인
--    이미 추가했으면 2, 아직이면 0 입니다.
--    2 면 아래 1번을 건너뛰세요 (실행하면 ORA-01430).
-- ---------------------------------------------------------
SELECT COUNT(*) AS already_added
FROM   user_tab_columns
WHERE  table_name  = 'USERS'
AND    column_name IN ('REFRESH_TOKEN_HASH', 'REFRESH_EXPIRES_AT');


-- ---------------------------------------------------------
-- 1. 컬럼 2개 추가
--
--    NOT NULL 을 붙이지 않는다
--      로그인한 적 없는 회원은 토큰이 없는 게 정상이다. NULL 이 "없음" 을
--      그대로 뜻한다. 로그아웃하면 다시 NULL 로 되돌린다.
--
--    TIMESTAMP(6) 에 UTC 로 넣는다
--      이 스키마의 모든 시각 컬럼과 같은 규칙이다 (01_schema.sql 상단 참고).
--      만료 판단은 서버가 하고, 저장할 때 SYS_EXTRACT_UTC 기준으로 맞춘다.
--
--    둘을 따로 두는 이유
--      JWT 안에도 만료 시각이 들어 있어서 중복처럼 보이지만, DB 에 따로 두면
--      SQL 만으로 "만료된 토큰 정리" 같은 일을 할 수 있다. 토큰을 일일이
--      풀어보지 않아도 되니 운영에서 편하다.
-- ---------------------------------------------------------
ALTER TABLE users ADD (
    refresh_token_hash  VARCHAR2(64 CHAR),
    refresh_expires_at  TIMESTAMP(6)
);

COMMENT ON COLUMN users.refresh_token_hash IS 'Refresh Token 의 SHA-256 해시(16진수 64글자). NULL = 로그아웃 상태';
COMMENT ON COLUMN users.refresh_expires_at IS 'Refresh Token 만료 시각 (UTC). 발급 시점 + 14일';


COMMIT;


