--
-- v2 에서 바뀌는 것
--   1. 논리 삭제 도입 — 6개 테이블에 USE_YN 추가 (VERIFICATION_CODES 는 제외)
--   2. UNIQUE 제약 -> 함수 기반 UNIQUE 인덱스로 교체
--      (평범한 UNIQUE 면 'N' 으로 남은 행 때문에 좋아요 재클릭 / Ban 재등록 /
--       탈퇴 이메일 재가입이 ORA-00001 로 막힌다)
--   3. POSTS -> RECIPE_REVIEWS 로 이름 변경, MEAL_HISTORIES 합성 FK 추가
--      (직접 만들어본 요리만 후기를 쓸 수 있게 DB 가 강제)
--   4. POST_LIKES -> REVIEW_LIKES, COMMENTS -> REVIEW_COMMENTS
--      (post_id -> review_id)
--   5. USERS 에 gender / 주소 4개 컬럼 추가 (대시보드 날씨 조회용)
--
-- ⚠️ 아래 4개 테이블은 DROP 후 재생성합니다.
--    MEAL_HISTORIES / POSTS / POST_LIKES / COMMENTS
--    바뀌는 구조가 많아 ALTER 로 옮기는 것보다 깨끗합니다.
--    데이터가 들어있다면 실행 전에 반드시 백업하세요. 아래로 먼저 확인합니다.
-- =========================================================


-- ---------------------------------------------------------
-- 0. 안전 확인 — 지워질 테이블에 데이터가 있는지 먼저 봅니다
--    전부 0 이어야 그냥 진행해도 됩니다. 0 이 아니면 백업부터 하세요.
-- ---------------------------------------------------------
SELECT (SELECT COUNT(*) FROM meal_histories) AS meal_histories,
       (SELECT COUNT(*) FROM posts)          AS posts,
       (SELECT COUNT(*) FROM post_likes)     AS post_likes,
       (SELECT COUNT(*) FROM comments)       AS comments
FROM   dual;


-- ---------------------------------------------------------
-- 1. 구버전 테이블 제거 (자식 -> 부모 순서)
-- ---------------------------------------------------------
DROP TABLE comments       CASCADE CONSTRAINTS PURGE;
DROP TABLE post_likes     CASCADE CONSTRAINTS PURGE;
DROP TABLE posts          CASCADE CONSTRAINTS PURGE;
DROP TABLE meal_histories CASCADE CONSTRAINTS PURGE;


-- ---------------------------------------------------------
-- 2. USERS — 컬럼 추가
--    기존 회원이 있으므로 gender / 주소는 NULL 허용이어야 한다.
--    use_yn 은 DEFAULT 'Y' 라 기존 행이 전부 'Y' 로 채워진다.
-- ---------------------------------------------------------
ALTER TABLE users ADD (
    gender           VARCHAR2(10 CHAR),
    address_sido     VARCHAR2(30 CHAR),
    address_sigungu  VARCHAR2(30 CHAR),
    latitude         NUMBER(9,6),
    longitude        NUMBER(9,6),
    use_yn           CHAR(1) DEFAULT 'Y' NOT NULL
);

ALTER TABLE users ADD CONSTRAINT ck_users_use_yn    CHECK (use_yn IN ('Y', 'N'));
ALTER TABLE users ADD CONSTRAINT ck_users_gender    CHECK (gender IS NULL OR gender IN ('MALE', 'FEMALE', 'OTHER'));
ALTER TABLE users ADD CONSTRAINT ck_users_latitude  CHECK (latitude  IS NULL OR latitude  BETWEEN  -90 AND  90);
ALTER TABLE users ADD CONSTRAINT ck_users_longitude CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180);


-- ---------------------------------------------------------
-- 3. USERS — UNIQUE 제약을 함수 기반 인덱스로 교체
--    제약조건을 DROP 하면 딸린 인덱스도 함께 사라져 같은 이름을 재사용할 수 있다.
-- ---------------------------------------------------------
ALTER TABLE users DROP CONSTRAINT uq_users_email;
ALTER TABLE users DROP CONSTRAINT uq_users_nickname;

CREATE UNIQUE INDEX uq_users_email    ON users (CASE WHEN use_yn = 'Y' THEN email    END);
CREATE UNIQUE INDEX uq_users_nickname ON users (CASE WHEN use_yn = 'Y' THEN nickname END);

-- 함수 기반 인덱스는 WHERE email = :v 조회에 쓰이지 않으므로 조회용을 따로 만든다
CREATE INDEX idx_users_email    ON users (email, use_yn);
CREATE INDEX idx_users_nickname ON users (nickname, use_yn);


-- ---------------------------------------------------------
-- 4. USER_BANS — USE_YN 추가 + UNIQUE 교체
-- ---------------------------------------------------------
ALTER TABLE user_bans ADD (use_yn CHAR(1) DEFAULT 'Y' NOT NULL);
ALTER TABLE user_bans ADD CONSTRAINT ck_user_bans_use_yn CHECK (use_yn IN ('Y', 'N'));

ALTER TABLE user_bans DROP CONSTRAINT uq_user_bans;

CREATE UNIQUE INDEX uq_user_bans ON user_bans (
    CASE WHEN use_yn = 'Y' THEN user_id         END,
    CASE WHEN use_yn = 'Y' THEN ingredient_name END
);

CREATE INDEX idx_user_bans_user ON user_bans (user_id, use_yn);


-- ---------------------------------------------------------
-- 5. MEAL_HISTORIES 재생성 (USE_YN + 합성 FK 참조용 UNIQUE 추가)
-- ---------------------------------------------------------
CREATE TABLE meal_histories (
    id                NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    user_id           NUMBER(19)          NOT NULL,
    food_name         VARCHAR2(150 CHAR)  NOT NULL,
    recipe_name       VARCHAR2(200 CHAR),
    recipe_json       CLOB                NOT NULL,
    ingredients_json  CLOB                NOT NULL,
    substitutes_json  CLOB,
    estimated_cost    NUMBER(10),
    use_yn            CHAR(1)             DEFAULT 'Y' NOT NULL,
    selected_at       TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_meal              PRIMARY KEY (id),
    CONSTRAINT fk_meal_user         FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_meal_id_user      UNIQUE (id, user_id),
    CONSTRAINT ck_meal_cost         CHECK (estimated_cost IS NULL OR estimated_cost >= 0),
    CONSTRAINT ck_meal_use_yn       CHECK (use_yn IN ('Y', 'N')),
    CONSTRAINT ck_meal_recipe_json  CHECK (recipe_json IS JSON),
    CONSTRAINT ck_meal_ingr_json    CHECK (ingredients_json IS JSON),
    CONSTRAINT ck_meal_subs_json    CHECK (substitutes_json IS NULL OR substitutes_json IS JSON)
);

CREATE INDEX idx_meal_user_selected ON meal_histories (user_id, use_yn, selected_at DESC);

COMMENT ON TABLE meal_histories IS '확정된 식사 스냅샷. AI가 나중에 다른 레시피를 생성해도 이 행은 변하지 않음';


-- ---------------------------------------------------------
-- 6. RECIPE_REVIEWS (구 POSTS)
--    food_name / recipe_json 컬럼은 없앴다. MEAL_HISTORIES 와 JOIN 해서 읽는다.
-- ---------------------------------------------------------
CREATE TABLE recipe_reviews (
    id               NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    user_id          NUMBER(19)          NOT NULL,
    meal_history_id  NUMBER(19)          NOT NULL,
    title            VARCHAR2(200 CHAR)  NOT NULL,
    content          CLOB                NOT NULL,
    view_count       NUMBER(10)          DEFAULT 0 NOT NULL,
    use_yn           CHAR(1)             DEFAULT 'Y' NOT NULL,
    created_at       TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    updated_at       TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_recipe_reviews      PRIMARY KEY (id),
    CONSTRAINT fk_reviews_user        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_reviews_meal        FOREIGN KEY (meal_history_id, user_id)
                                      REFERENCES meal_histories (id, user_id),
    CONSTRAINT ck_reviews_view_count  CHECK (view_count >= 0),
    CONSTRAINT ck_reviews_use_yn      CHECK (use_yn IN ('Y', 'N'))
);

CREATE UNIQUE INDEX uq_reviews_meal ON recipe_reviews (
    CASE WHEN use_yn = 'Y' THEN meal_history_id END
);

CREATE INDEX idx_reviews_created ON recipe_reviews (use_yn, created_at DESC);
CREATE INDEX idx_reviews_user    ON recipe_reviews (user_id, use_yn);

COMMENT ON TABLE recipe_reviews IS '레시피 후기 게시판. 자기 MEAL_HISTORIES 에서만 작성 가능. 조회는 Guest 가능';


-- ---------------------------------------------------------
-- 7. REVIEW_LIKES (구 POST_LIKES)
-- ---------------------------------------------------------
CREATE TABLE review_likes (
    id          NUMBER(19)  GENERATED BY DEFAULT AS IDENTITY,
    user_id     NUMBER(19)  NOT NULL,
    review_id   NUMBER(19)  NOT NULL,
    use_yn      CHAR(1)     DEFAULT 'Y' NOT NULL,
    created_at  TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_review_likes        PRIMARY KEY (id),
    CONSTRAINT fk_review_likes_user   FOREIGN KEY (user_id)   REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_review_likes_review FOREIGN KEY (review_id) REFERENCES recipe_reviews (id) ON DELETE CASCADE,
    CONSTRAINT ck_review_likes_use_yn CHECK (use_yn IN ('Y', 'N'))
);

CREATE UNIQUE INDEX uq_review_likes ON review_likes (
    CASE WHEN use_yn = 'Y' THEN user_id   END,
    CASE WHEN use_yn = 'Y' THEN review_id END
);

CREATE INDEX idx_review_likes_review ON review_likes (review_id, use_yn);

COMMENT ON TABLE review_likes IS '좋아요. 취소는 use_yn=N. 자기 후기에도 가능';


-- ---------------------------------------------------------
-- 8. REVIEW_COMMENTS (구 COMMENTS)
-- ---------------------------------------------------------
CREATE TABLE review_comments (
    id          NUMBER(19)           GENERATED BY DEFAULT AS IDENTITY,
    review_id   NUMBER(19)           NOT NULL,
    user_id     NUMBER(19)           NOT NULL,
    content     VARCHAR2(1000 CHAR)  NOT NULL,
    use_yn      CHAR(1)              DEFAULT 'Y' NOT NULL,
    created_at  TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    updated_at  TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT pk_review_comments       PRIMARY KEY (id),
    CONSTRAINT fk_review_comments_rev   FOREIGN KEY (review_id) REFERENCES recipe_reviews (id) ON DELETE CASCADE,
    CONSTRAINT fk_review_comments_user  FOREIGN KEY (user_id)   REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_review_comments_useyn CHECK (use_yn IN ('Y', 'N'))
);

CREATE INDEX idx_review_comments_rev ON review_comments (review_id, use_yn, created_at);

COMMENT ON TABLE review_comments IS '댓글. 대댓글 미지원(MVP). 삭제는 use_yn=N';


