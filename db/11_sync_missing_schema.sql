CREATE TABLE post_comments (
    id          NUMBER(19)           GENERATED BY DEFAULT AS IDENTITY,        
    board_type  CHAR(1)              DEFAULT 'R' NOT NULL,                    
    post_id     NUMBER(19)           NOT NULL,                                
    user_id     NUMBER(19)           NOT NULL,                                
    content     VARCHAR2(1000 CHAR)  NOT NULL,                                
    use_yn      CHAR(1)              DEFAULT 'Y' NOT NULL,                    
    created_at  TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  
    updated_at  TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  
    CONSTRAINT pk_post_comments       PRIMARY KEY (id),
    CONSTRAINT fk_post_comments_user  FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_post_comments_board CHECK (board_type IN ('R', 'F')),
    CONSTRAINT ck_post_comments_useyn CHECK (use_yn IN ('Y', 'N'))
);

CREATE INDEX idx_post_comments_post ON post_comments (board_type, post_id, use_yn, created_at);

COMMENT ON TABLE  post_comments IS '댓글. 레시피리뷰(R)와 자유게시판(F)이 같이 쓴다. 대댓글 미지원. 삭제는 use_yn=N';

COMMENT ON COLUMN post_comments.board_type IS '어느 게시판의 댓글인지. R=RECIPE_REVIEWS, F=FREE_POSTS';

CREATE TABLE recipe_likes (
    id          NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,         
    user_id     NUMBER(19)          NOT NULL,                                 
    food_name   VARCHAR2(150 CHAR)  NOT NULL,                                 
    use_yn      CHAR(1)             DEFAULT 'Y' NOT NULL,                     
    created_at  TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  
    CONSTRAINT pk_recipe_likes        PRIMARY KEY (id),
    CONSTRAINT fk_recipe_likes_user   FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_recipe_likes_use_yn CHECK (use_yn IN ('Y', 'N'))
);

CREATE UNIQUE INDEX uq_recipe_likes ON recipe_likes (
    CASE WHEN use_yn = 'Y' THEN user_id   END,
    CASE WHEN use_yn = 'Y' THEN food_name END
);

CREATE INDEX idx_recipe_likes_user ON recipe_likes (user_id, use_yn);

COMMENT ON TABLE  recipe_likes IS '찜한 레시피. 해제는 use_yn=N. 로그인한 회원만 찜할 수 있다';

COMMENT ON COLUMN recipe_likes.food_name IS '음식 이름. 추천 결과를 저장하지 않으므로 id 가 없다';

CREATE TABLE free_posts (
    id             NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,         
    user_id        NUMBER(19)          NOT NULL,                                 
    title          VARCHAR2(200 CHAR)  NOT NULL,                                 
    content        CLOB                NOT NULL,                                 
    file_yn        CHAR(1)             DEFAULT 'N' NOT NULL,                     
    file_name      VARCHAR2(255 CHAR),                                           
    file_org_name  VARCHAR2(255 CHAR),                                           
    file_path      VARCHAR2(500 CHAR),                                           
    file_ext       VARCHAR2(20 CHAR),                                            
    file_size      NUMBER(19),                                                   
    view_count     NUMBER(10)          DEFAULT 0 NOT NULL,                       
    use_yn         CHAR(1)             DEFAULT 'Y' NOT NULL,                     
    created_at     TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  
    updated_at     TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,  
    CONSTRAINT pk_free_posts            PRIMARY KEY (id),
    CONSTRAINT fk_free_posts_user       FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_free_posts_view_count CHECK (view_count >= 0),
    CONSTRAINT ck_free_posts_use_yn     CHECK (use_yn IN ('Y', 'N')),
    CONSTRAINT ck_free_posts_file_yn    CHECK (file_yn IN ('Y', 'N')),
    CONSTRAINT ck_free_posts_file_size  CHECK (file_size IS NULL OR file_size >= 0),
    CONSTRAINT ck_free_posts_file_set   CHECK (
        (file_yn = 'N' AND file_name IS NULL AND file_org_name IS NULL
                       AND file_path IS NULL AND file_ext  IS NULL AND file_size IS NULL)
     OR (file_yn = 'Y' AND file_name IS NOT NULL AND file_org_name IS NOT NULL
                       AND file_path IS NOT NULL AND file_ext  IS NOT NULL))
);

CREATE INDEX idx_free_posts_created ON free_posts (use_yn, created_at DESC);

CREATE INDEX idx_free_posts_user ON free_posts (user_id, use_yn);

COMMENT ON TABLE  free_posts IS '자유게시판. 로그인한 회원이면 주제 제한 없이 작성. 조회는 Guest 가능. 첨부파일은 FILE_* 컬럼에 1건 보관(별도 테이블 없음)';

COMMENT ON COLUMN free_posts.user_id IS '글쓴이. RECIPE_REVIEWS 와 달리 부모 식사기록이 없어 FK 는 이것 하나다';
