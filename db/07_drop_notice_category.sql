-- 실행 계정 : MEOKJI_APP
-- 실행 방법 : 파일 전체 선택 후 Alt+X (DBeaver) / F5 (SQL Developer)
--             ※ Ctrl+Enter 는 한 문장만 실행합니다
--
-- 왜 없애나요?
--   분류 배지('안내' · '점검' · '업데이트')를 쓰지 않기로 했습니다.
--   공지는 공지 하나로 충분하고, 분류가 늘어날 계획도 없습니다.
--
--   값을 강제하는 장치가 어차피 없었습니다 — CHECK 도, 분류 목록을 담은
--   표도 두지 않았습니다. 선택지는 화면의 드롭다운에만 적혀 있었고,
--   화면도 '점검' 하나만 경고색으로 그리고 나머지는 전부 같은 모양이었습니다.
--   그 한 가지를 위해 컬럼 하나와 화면 코드를 유지할 이유가 없습니다.
--
--   테이블 개수는 그대로 9개입니다.
--
-- 지워지는 값
--   기존 공지의 분류 문자열이 사라집니다. 되돌릴 수 없습니다.
--   공지의 제목 · 본문 · 조회수 · 고정 여부는 그대로입니다.
--
-- 되돌리려면
--   ALTER TABLE notices ADD (category VARCHAR2(20 CHAR) DEFAULT '안내' NOT NULL);
--   (값은 전부 '안내' 가 됩니다. 원래 분류는 복구되지 않습니다)
-- =========================================================


-- ---------------------------------------------------------
-- 0. 실행 전 확인
--    CATEGORY 가 아직 있으면 1, 이미 지웠으면 0 입니다.
--    0 이면 이 파일을 실행할 필요가 없습니다 (실행하면 ORA-00904).
-- ---------------------------------------------------------
SELECT COUNT(*) AS category_still_there
FROM   user_tab_columns
WHERE  table_name  = 'NOTICES'
AND    column_name = 'CATEGORY';


-- ---------------------------------------------------------
-- 1. 컬럼 삭제
--
--    DROP COLUMN 은 딸린 제약과 인덱스를 같이 정리한다.
--    이 컬럼에는 CHECK 를 걸지 않았고 인덱스도 없어서 이 한 줄이면 끝난다.
-- ---------------------------------------------------------
ALTER TABLE notices DROP COLUMN category;


COMMIT;


