# 단위 하나의 무게. COUNT_GRAMS 에 없는 재료와 계량 단위에 쓴다.
GRAMS_PER_UNIT = {
    "g": 1, "ml": 1,
    "큰술": 15, "작은술": 5, "컵": 200, "공기": 210,
    "모": 300, "토막": 80, "대": 80, "장": 3,
}


def portion_for(name: str) -> tuple[float, str]:
    """재료 하나의 분량과 단위. 표에 없으면 기본값."""
    return PORTIONS.get(name, DEFAULT_PORTION)


def grams_for(name: str, quantity: float, unit: str) -> float:
    """그 분량이 몇 그램인지."""
    per = COUNT_GRAMS.get(name)
    if per is not None and unit in ("개", "마리", "포기", "구", "알", "통", "장"):
        return round(quantity * per, 1)

    return round(quantity * GRAMS_PER_UNIT.get(unit, 100), 1)
