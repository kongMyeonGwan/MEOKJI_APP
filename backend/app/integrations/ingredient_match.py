def strip_parentheses(name: str) -> str:
    """괄호와 그 안의 설명을 떼어낸다.  '밀가루 (중력분)' -> '밀가루'"""
    return re.sub(r"[（(\[][^）)\]]*[）)\]]", " ", name)


def normalize(name: str) -> str:
    """비교하기 좋은 형태로 다듬는다.

    괄호를 떼고, 손질 표현을 떼고, 공백을 없앤다.
    공백을 없애는 이유는 '다진 마늘' 과 '다진마늘' 이 같은 말이기 때문이다.
    """
    text = strip_parentheses(str(name or "")).strip()

    # 낱말 단위로 손질 표현과 용도 표현을 떼어낸다
    words = []
    for word in text.split():
        if word in MODIFIERS:
            continue
        if any(word.endswith(suffix) and len(word) > 1 for suffix in PURPOSE_SUFFIXES):
            continue
        words.append(word)

    text = "".join(words) if words else text.replace(" ", "")

    # 붙여 쓴 손질 표현도 뗀다 ("다진마늘" -> "마늘")
    #
    # 떼고 난 것이 품목표에 없으면 되돌린다
    # -------------------------------------
    # '생강' 은 '생' + '강' 이 아니라 그 자체가 품목이다. 그냥 떼면 '강' 이
    # 되어 영영 못 찾는다. 실제로 116종 중 이 한 종이 그랬다.
    #
    # 그래서 "떼어낸 결과가 아는 품목일 때만" 뗀다. 아니면 원래대로 둔다.
    # '다진마늘' 은 떼면 '마늘' 이라 품목표에 있으니 그대로 통과한다.
    changed = True
    while changed:
        changed = False
        for modifier in MODIFIERS:
            if not text.startswith(modifier) or len(text) <= len(modifier):
                continue

            stripped = text[len(modifier):]

            # 떼기 전 이름이 이미 품목이면 건드리지 않는다 ('생강')
            if text in KAMIS_ITEM_CODES:
                break

            text = stripped
            changed = True
            break

    return text


def is_not_priced(name: str) -> bool:
    """가격을 물어볼 대상이 아닌지. 물·얼음 같은 것."""
    text = normalize(name)

    if text in NOT_PRICED:
        return True

    # "멸치 다시마 육수용 물" 처럼 마지막 낱말이 물인 경우
    words = strip_parentheses(str(name or "")).split()
    return bool(words) and words[-1] in NOT_PRICED


