# 한 글자짜리(김·무·배·파·감·게·닭·콩)는 부분일치에서 뺀다.
# '김치' 에서 '김' 을, '배추' 에서 '배' 를 찾아버리기 때문이다.
# 그런 이름은 정확히 일치할 때만 쓴다.
_PARTIAL_KEYS = sorted(
    (key for key in KAMIS_ITEM_CODES if len(key) >= 2),
    key=len,
    reverse=True,
)


def find_codes(name: str) -> tuple[str, str, str | None] | None:
    """재료명으로 KAMIS 코드를 찾는다. 못 찾으면 None.

    네 단계로 시도한다. 위에서 찾으면 아래는 보지 않는다.

        1. 다듬은 이름이 그대로 품목표에 있는가      "마늘"
        2. 별칭표에 있는가                          "청양고추" -> "고추"
        3. 품목명이 이름 안에 들어 있는가            "돼지고기앞다리살" -> "돼지고기"
        4. 없음
    """
    text = normalize(name)
    if not text:
        return None

    codes = KAMIS_ITEM_CODES.get(text)
    if codes is not None:
        return codes

    alias = ALIASES.get(text)
    if alias is not None:
        return KAMIS_ITEM_CODES.get(alias)

    # 가공식품은 원물 시세를 빌려 쓰면 안 된다. 부분일치에 넘기지 않는다.
    if text in PROCESSED:
        return None

    # 가장 긴 품목명부터 찾는다. '양파' 를 '파' 로 잡으면 안 된다.
    for key in _PARTIAL_KEYS:
        if key in text:
            return KAMIS_ITEM_CODES[key]

    return None


def vocabulary() -> list[str]:
    """AI 프롬프트에 넣을 KAMIS 품목명 목록.

    "이 단어를 쓰라"고 알려주면 AI 가 애초에 맞는 이름을 적어준다.
    뒤에서 우리가 맞춰보는 것보다 앞에서 맞추는 편이 잘 맞는다.
    """
    return sorted(KAMIS_ITEM_CODES)
