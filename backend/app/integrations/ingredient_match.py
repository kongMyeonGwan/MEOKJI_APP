def strip_parentheses(name: str) -> str:
    """괄호와 그 안의 설명을 떼어낸다.  '밀가루 (중력분)' -> '밀가루'"""
    return re.sub(r"[（(\[][^）)\]]*[）)\]]", " ", name)


def normalize(name: str) -> str:
    """비교하기 좋은 형태로 다듬는다."""
    text = strip_parentheses(str(name or "")).strip()

    # 낱말 단위로 손질 표현과 용도 표현을 떼어낸다
    words = []
    for word in text.split():
        if word in MODIFIERS:
            continue
        if any(word.endswith(suffix) and len(word) > 1 for suffix in PURPOSE_SUFFIXES):
            continue
        words.append(word)

    text = "".join(words) if words else text.replace(" ", "")

    # 붙여 쓴 손질 표현도 뗀다 ("다진마늘" -> "마늘")
    changed = True
    while changed:
        changed = False
        for modifier in MODIFIERS:
            if not text.startswith(modifier) or len(text) <= len(modifier):
                continue

            stripped = text[len(modifier):]

            # 떼기 전 이름이 이미 품목이면 건드리지 않는다 ('생강')
            if text in KAMIS_ITEM_CODES:
                break

            text = stripped
            changed = True
            break

    return text


def is_not_priced(name: str) -> bool:
    """가격을 물어볼 대상이 아닌지. 물·얼음 같은 것."""
    text = normalize(name)

    if text in NOT_PRICED:
        return True

    # "멸치 다시마 육수용 물" 처럼 마지막 낱말이 물인 경우
    words = strip_parentheses(str(name or "")).split()
    return bool(words) and words[-1] in NOT_PRICED


# 부분일치에 쓸 후보. 짧은 이름이 긴 이름을 가로채지 않게 긴 것부터 본다.
_PARTIAL_KEYS = sorted(
    (key for key in KAMIS_ITEM_CODES if len(key) >= 2),
    key=len,
    reverse=True,
)


def find_codes(name: str) -> tuple[str, str, str | None] | None:
    """재료명으로 KAMIS 코드를 찾는다."""
    text = normalize(name)
    if not text:
        return None

    codes = KAMIS_ITEM_CODES.get(text)
    if codes is not None:
        return codes

    alias = ALIASES.get(text)
    if alias is not None:
        return KAMIS_ITEM_CODES.get(alias)

    # 가공식품은 원물 시세를 빌려 쓰면 안 된다. 부분일치에 넘기지 않는다.
    if text in PROCESSED:
        return None

    # 가장 긴 품목명부터 찾는다. '양파' 를 '파' 로 잡으면 안 된다.
    for key in _PARTIAL_KEYS:
        if key in text:
            return KAMIS_ITEM_CODES[key]

    return None


def vocabulary() -> list[str]:
    """AI 프롬프트에 넣을 KAMIS 품목명 목록."""
    return sorted(KAMIS_ITEM_CODES)
