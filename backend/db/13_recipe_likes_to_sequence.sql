-- =========================================================
-- RECIPE_LIKES(찜) : PK 를 IDENTITY -> 시퀀스(RECIPE_LIKES_SEQ) 로 바꾼다
--
-- 언제 실행하나요?
--   01_schema.sql / 08_add_recipe_likes.sql 로 RECIPE_LIKES 를 만든 DB 에서,
--   찜 기능을 JPA(@SequenceGenerator)로 구현하기 전에 실행합니다.
--   여러 번 돌려도 안전합니다 — 이미 바뀐 DB 면 아무것도 하지 않고 끝납니다.
--
-- 실행 계정 : MEOKJI_APP
-- 실행 방법 : 파일 전체 선택 후 Alt+X (DBeaver) / F5 (SQL Developer)
--             ※ Ctrl+Enter 는 한 문장만 실행합니다
--
-- 무엇이 바뀌나요?
--   1. recipe_likes.id 에서 IDENTITY 를 뗀다. 컬럼 · PK · 들어 있는 찜은 그대로다.
--      IDENTITY 가 속으로 만들어 둔 시퀀스(ISEQ$$_...)는 이때 같이 사라진다.
--   2. RECIPE_LIKES_SEQ 시퀀스를 만든다. 지금 가장 큰 id 다음 번호부터 시작한다 —
--      1 부터 시작하면 이미 있는 찜과 번호가 겹쳐 INSERT 가 PK 위반으로 막힌다.
--
-- JPA 엔티티와 짝 (allocationSize = 1 이라 INCREMENT BY 1 이다)
--   @Id
--   @GeneratedValue(strategy = GenerationType.SEQUENCE, generator = "recipe_likes_seq_generator")
--   @SequenceGenerator(
--           name = "recipe_likes_seq_generator", // Java 안에서 부르는 이름
--           sequenceName = "RECIPE_LIKES_SEQ",   // Oracle 시퀀스 이름
--           allocationSize = 1)
--   private Long id;
--
-- 되돌리려면 (찜이 있으면 START WITH 를 MAX(id)+1 로 맞춰야 한다)
--   DROP SEQUENCE recipe_likes_seq;
--   ALTER TABLE recipe_likes MODIFY (id GENERATED BY DEFAULT AS IDENTITY (START WITH <MAX(id)+1>));
--
-- 주석 바로 아래에 빈 줄을 두지 않았다. DBeaver 는 빈 줄을 문장 구분자로 볼 수 있어서
-- 주석만 있는 덩어리가 Oracle 로 넘어가면 ORA-00900 이 난다.
-- =========================================================
-- 0. 실행 전 확인
--    identity_column 이 YES 면 바꿀 대상, NO 면 이미 바뀐 것이다.
-- ---------------------------------------------------------
SELECT column_name, identity_column
FROM   user_tab_columns
WHERE  table_name = 'RECIPE_LIKES'
AND    column_name = 'ID';

-- ---------------------------------------------------------
-- 1. IDENTITY 떼기 + 2. 시퀀스 만들기
--    START WITH 에는 변수를 못 쓰므로 PL/SQL 로 문장을 만들어 실행한다.
--    이미 된 단계는 건너뛰어서 다시 돌려도 ORA-30673 / ORA-00955 가 나지 않는다.
-- ---------------------------------------------------------
DECLARE
    v_identity  VARCHAR2(3);
    v_seq_count NUMBER;
    v_start     NUMBER;
BEGIN
    SELECT identity_column INTO v_identity
    FROM   user_tab_columns
    WHERE  table_name = 'RECIPE_LIKES'
    AND    column_name = 'ID';

    IF v_identity = 'YES' THEN
        EXECUTE IMMEDIATE 'ALTER TABLE recipe_likes MODIFY (id DROP IDENTITY)';
        DBMS_OUTPUT.PUT_LINE('RECIPE_LIKES.ID : IDENTITY 제거');
    ELSE
        DBMS_OUTPUT.PUT_LINE('RECIPE_LIKES.ID : 이미 IDENTITY 아님 - 건너뜀');
    END IF;

    SELECT COUNT(*) INTO v_seq_count
    FROM   user_sequences
    WHERE  sequence_name = 'RECIPE_LIKES_SEQ';

    IF v_seq_count = 0 THEN
        SELECT NVL(MAX(id), 0) + 1 INTO v_start FROM recipe_likes;

        EXECUTE IMMEDIATE 'CREATE SEQUENCE recipe_likes_seq START WITH ' || v_start
                       || ' INCREMENT BY 1 NOCACHE';

        DBMS_OUTPUT.PUT_LINE('RECIPE_LIKES_SEQ starts with ' || v_start);
    ELSE
        DBMS_OUTPUT.PUT_LINE('RECIPE_LIKES_SEQ : 이미 있음 - 건너뜀');
    END IF;
END;
/

COMMENT ON COLUMN recipe_likes.id IS 'PK. RECIPE_LIKES_SEQ 시퀀스로 채운다 (IDENTITY 아님)';

-- ---------------------------------------------------------
-- 3. 실행 결과 확인
--    identity_column = NO, last_number > max_id 이면 정상
-- ---------------------------------------------------------
SELECT c.identity_column,
       s.sequence_name,
       s.increment_by,
       s.last_number,
       (SELECT NVL(MAX(id), 0) FROM recipe_likes) AS max_id
FROM   user_tab_columns c
LEFT JOIN user_sequences s ON s.sequence_name = 'RECIPE_LIKES_SEQ'
WHERE  c.table_name = 'RECIPE_LIKES'
AND    c.column_name = 'ID';
