-- 시각은 전부 UTC 다. 주석의 KST 시각에서 9시간을 뺀 값이다.
--
-- 주석 바로 아래에 빈 줄을 두지 않았다. DBeaver 는 빈 줄을 문장 구분자로 볼 수 있어서
