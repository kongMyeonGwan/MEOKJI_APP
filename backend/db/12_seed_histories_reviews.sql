--
-- CLOB 을 TO_CLOB('...') || TO_CLOB('...') 조각으로 넣는 이유
--   SQL 문자열 리터럴은 4000바이트가 한계다(ORA-01704). 한글은 글자당 3바이트라
--   조리 순서가 긴 레시피는 한 덩어리로 넣으면 막힌다. 조각마다 900자 이하로 잘랐다.
