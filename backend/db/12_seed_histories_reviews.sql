--   ingredients_json [{name, quantity, unit, grams}, ...]
--   substitutes_json [{original, substitute, reason}, ...]  없으면 []
-- 일부 기록에는 양파 · 오이 대체재료가 붙어 있다. 히스토리는 확정 당시 스냅샷이라
