package com.meokji.api.free.entity;

import java.time.LocalDateTime;
import java.time.ZoneOffset;

import jakarta.persistence.*;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;

/**
 * FREE_POSTS 표 한 행 — JPA 가 쓰고 지울 때만 쓰는 클래스.
 *
 * FreePostVO 와 역할이 다르다. VO 는 화면과 주고받는 모양이고, 이쪽은
 * JPA 가 영속성을 관리하는 대상이다. 둘을 한 클래스로 겸하지 않는다 —
 * VO 에는 표에 없는 칸(닉네임 · 댓글 · 첨부 · is_mine)이 들어 있어서
 * JPA 가 관리할 수 있는 모양이 아니다.
 *
 * 이 글의 일 중에서 JPA 가 맡는 것은 셋뿐이다.
 *   글쓰기 · 글 수정 · 글 삭제(use_yn='N')
 * 목록 · 검색 · 페이징 · 조회수 · 댓글 · 첨부는 전부 MyBatis 가 한다.
 *
 * 표에 있는데 여기 없는 칸
 *
 *   FILE_* 여섯 칸을 일부러 뺐다. 첨부는 MyBatis 가 맡는데, 여기 적어두면
 *   글 제목만 고쳐도 하이버네이트가 매핑된 칸을 전부 UPDATE 에 실어서
 *   붙어 있던 사진 정보를 null 로 덮어쓴다. 안 적으면 UPDATE 문에
 *   아예 안 들어간다.
 *
 * 쓰지 않는 칸에 insertable · updatable = false 를 붙인 이유
 *
 *   viewCount  조회수는 MyBatis 가 view_count + 1 로만 올린다. 여기서
 *              같이 써버리면, 수정하는 사이에 누가 글을 열었을 때 그
 *              조회수가 옛 값으로 되돌아간다.
 *   createdAt  DB 기본값 SYS_EXTRACT_UTC(SYSTIMESTAMP) 가 채운다.
 *
 * 시각은 UTC 다
 *
 *   DB 가 UTC 로 적고(위 기본값), 커넥션도 UTC 로 맞춰져 있다.
 *   그래서 수정 시각을 넣을 때 LocalDateTime.now() 를 쓰면 안 된다 —
 *   그 값은 한국 시간이라 아홉 시간 뒤로 적힌다. now(ZoneOffset.UTC) 다.
 */
@Entity
@Table(name = "free_posts")
@Getter
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class FreePostEntity {

    /**
     * 오라클 IDENTITY 다 (GENERATED BY DEFAULT AS IDENTITY).
     * 시퀀스를 직접 만들거나 트리거로 채우지 않는다 — DB 에 물어 확인했다.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.SEQUENCE, generator = "free_seq_generator")
    @SequenceGenerator(
            name ="free_seq_generator", // JAVA 안에서 부르는 이름
            sequenceName = "FREE_SEQ",  // Oracle 시퀀스 이름
            allocationSize = 1
    )
    private Long id;    // 글번호

    /** 글쓴이. 한 번 정해지면 안 바뀐다 
      * 작성자(글 여러개: 회원 한명)
     * @ManyToone: 1:N
     * @fetch = FetchType.LAZY: 실제 사용할 때 DB에서 가져옴
     * @JoinColumn: Member table과 조인
     * */
    @Column(name = "user_id", nullable = false, updatable = false)
    private Long userId;

    @Column(name = "title", nullable = false, length = 200)
    private String title;

    /** CLOB 이다. 4000자까지 받으므로 VARCHAR2 로는 안 들어간다 */
    @Lob
    @Column(name = "content", nullable = false)
    private String content;

    /** 읽기만 한다. 올리는 것은 MyBatis 의 increaseView 다 */
    @Column(name = "view_count", insertable = false, updatable = false)
    private Integer viewCount;

    @Column(name = "use_yn", nullable = false, length = 1)
    private String useYn;

    /** 읽기만 한다. DB 기본값이 넣는다 */
    @Column(name = "created_at", insertable = false, updatable = false)
    private LocalDateTime createdAt;

    @Column(name = "updated_at")
    private LocalDateTime updatedAt;

    /** 새 글. id · 조회수 · 작성 시각은 DB 가 채운다 */
    public static FreePostEntity create(Long userId, String title, String content) {
        FreePostEntity post = new FreePostEntity();
        post.userId = userId;
        post.title = title;
        post.content = content;
        post.useYn = "Y";
        post.updatedAt = nowUtc();
        return post;
    }

    /**
     * 제목 · 내용 고치기.
     *
     * 이 메서드만 부르면 UPDATE 가 나간다. 트랜잭션이 끝날 때 JPA 가
     * 처음 읽어둔 값과 견주어 달라진 칸을 찾아 스스로 보낸다(변경 감지).
     * save() 를 다시 부를 필요가 없다.
     */
    public void change(String title, String content) {
        this.title = title;
        this.content = content;
        this.updatedAt = nowUtc();
    }

    /**
     * 삭제. 행을 지우지 않고 use_yn='N' 으로 바꾼다.
     *
     * deleteById() 를 쓰면 행이 사라져서 댓글 · 좋아요가 가리킬 곳을 잃는다.
     */
    public void deactivate() {
        this.useYn = "N";
        this.updatedAt = nowUtc();
    }

    /** DB 가 UTC 로 적으므로 여기서 넣는 값도 UTC 여야 한다 */
    private static LocalDateTime nowUtc() {
        return LocalDateTime.now(ZoneOffset.UTC);
    }
}
